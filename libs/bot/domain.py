@dataclass
class SimulatedPosition:
    """Represents a virtual asset position in the simulation portfolio."""
    symbol: str = ""
    qty: float = 0.0
    avg_entry_price: float = 0.0
    current_price: float = 0.0
    cost_basis: float = 0.0
    market_value: float = 0.0
    unrealized_pnl: float = 0.0
    realized_pnl: float = 0.0
    updated_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    environment: str = "SIMULATION"

    @property
    def quantity(self) -> float:
        return self.qty

    def recalculate(self, latest_price: float) -> None:
        """Updates market value and unrealized PnL based on latest market price."""
        self.current_price = latest_price
        self.market_value = self.qty * self.current_price
        self.cost_basis = self.qty * self.avg_entry_price
        self.unrealized_pnl = self.market_value - self.cost_basis
        self.updated_at = datetime.now(timezone.utc)


