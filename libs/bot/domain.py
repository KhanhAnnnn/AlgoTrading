    initial_cash: float = 100000.0
    risk_config_hash: str = ""
    execution_config_hash: str = ""
    data_consumer_group: str = "paper-bot-v2-group"
    status: str = "STOPPED"  # STOPPED, STARTING, RUNNING, PAUSED, STOPPING, ERROR
    lifecycle_state: str = "STOPPED"
    start_time: Optional[datetime] = None
    started_at: Optional[datetime] = None
    paused_at: Optional[datetime] = None
    end_time: Optional[datetime] = None
    stopped_at: Optional[datetime] = None
    last_heartbeat_at: Optional[datetime] = None
    last_processed_event_id: str = ""
    last_processed_bar_key: str = ""
    checkpoint_id: str = ""
    error_code: Optional[str] = None
    error_message: Optional[str] = None
    created_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    environment: str = "SIMULATION"
    trading_mode: str = "DRY_RUN"
    metadata: Dict[str, Any] = field(default_factory=dict)

